#!/usr/bin/env python3
"""Turns the generated images (ART.md: prompts, seeds, raw files) into the stage2 assets, deterministically:
  plate.webp     the night scene, 1024 -> 2048 (Lanczos, a light unsharp mask), WebP q90
  depth.png      its depth map (white near), near values dilated 2 px then blurred, so a moving edge carries its own background
  p-<name>.webp  each portrait keyed off its flat green: alpha from the green excess, the green un-mixed out of the edge pixels,
                 the residual spill clamped near the edge only (the tutor's coat is green), 1024 -> 1200, WebP q92 with alpha
  art.js         plate and depth as data URLs (WebGL cannot read an image file from a file:// page; a data URL it can)
  usage: python3 -I art.py assets/src assets     assets/src holds the raw generations: bg-1.jpg depth-1.jpg p-<name>-1.jpg
FAILURE MODE IT BLOCKS: a portrait whose key leaves a green fringe or eats into the figure; it exits 1 when a portrait keeps more than
0.5 % green-dominant pixels in its opaque part, or when less than 20 % or more than 85 % of the frame stays opaque."""
import base64
import io
import os
import sys

import numpy as np
from PIL import Image, ImageFilter

NAMES = ("suzanne", "tsukumo", "herve", "haku")
KEY = np.array([0.0, 255.0, 0.0])


def key(img):
    a = np.asarray(img.convert("RGB"), dtype=np.float32)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    spill = g - np.maximum(r, b)
    alpha = 1.0 - np.clip((spill - 40.0) / 70.0, 0.0, 1.0)
    alpha = np.clip((alpha - 0.08) / 0.92, 0.0, 1.0)
    # un-mix the key from partly covered pixels: C = aF + (1 - a)K  ->  F = (C - (1 - a)K) / a
    part = (alpha > 0.04) & (alpha < 0.999)
    fg = a.copy()
    am = alpha[part][:, None]
    fg[part] = np.clip((a[part] - (1.0 - am) * KEY) / am, 0.0, 255.0)
    # clamp what green is left, but only within 4 px of the background, so a green coat keeps its colour
    bgmask = Image.fromarray(((alpha < 0.5) * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(9))
    near = np.asarray(bgmask) > 0
    g2 = np.minimum(fg[..., 1], np.maximum(fg[..., 0], fg[..., 2]) + 6.0)
    fg[..., 1] = np.where(near, g2, fg[..., 1])
    out = np.dstack([fg, alpha * 255.0]).round().clip(0, 255).astype(np.uint8)
    return Image.fromarray(out, "RGBA")


def check(name, im):
    a = np.asarray(im, dtype=np.float32)
    opaque = a[..., 3] > 200
    share = opaque.mean()
    green = (a[..., 1] > np.maximum(a[..., 0], a[..., 2]) + 40) & opaque
    gshare = green.sum() / max(1, opaque.sum())
    print("art: p-%s opaque %.1f %%, green-dominant in it %.3f %%" % (name, share * 100, gshare * 100))
    return 0.20 <= share <= 0.85 and gshare <= 0.005


def data_url(path, mime):
    return "data:%s;base64,%s" % (mime, base64.b64encode(open(path, "rb").read()).decode())


def main():
    raw, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    plate = Image.open(os.path.join(raw, "bg-1.jpg")).convert("RGB").resize((2048, 2048), Image.LANCZOS)
    plate = plate.filter(ImageFilter.UnsharpMask(radius=2.2, percent=60, threshold=2))
    plate.save(os.path.join(out, "plate.webp"), "WEBP", quality=90, method=6)
    depth = Image.open(os.path.join(raw, "depth-1.jpg")).convert("L").filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(2.0))
    depth.save(os.path.join(out, "depth.png"), "PNG", optimize=True)
    ok = True
    for n in NAMES:
        im = key(Image.open(os.path.join(raw, "p-%s-1.jpg" % n))).resize((1200, 1200), Image.LANCZOS)
        ok = check(n, im) and ok
        im.save(os.path.join(out, "p-%s.webp" % n), "WEBP", quality=92, method=6)
    js = "// Generated by art.py from plate.webp and depth.png: the scene's textures as data URLs, so WebGL may read them on a file:// page.\n"
    js += "window.STAGE2_ART = {\n  plate: \"%s\",\n  depth: \"%s\",\n};\n" % (
        data_url(os.path.join(out, "plate.webp"), "image/webp"), data_url(os.path.join(out, "depth.png"), "image/png"))
    open(os.path.join(out, "art.js"), "w").write(js)
    for f in sorted(f for f in os.listdir(out) if os.path.isfile(os.path.join(out, f))):
        print("art: %s %d KB" % (f, os.path.getsize(os.path.join(out, f)) // 1024))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
