"""The hero's reads (round shapestab, 2026-10-22): the picker's vn read of the stage as it stood under the pointer in the film take, as a Swift fixture
for LensShapeStabilityTests.  The reads are hero2o's (tools/first-lens/data/shapes/hero/): h0, hc0..hc3 are the stage (hero.html, 1512 x 839 pt, 1:1)
pasted into the live screen frame dy = 0..3 pt lower and read again (Vision's boxes move by a point or two and sometimes merge or lose a block);
zc is the zoom case (index.html at 0.888) read the same way; live is the block list of the live take at that zoom (a trace, no word boxes).
Screen points, 2 px per point in the dumps.  Each multi-line block carries `head`, its first line's box (the words of the first line of the
dump's `w`); live has none, but its dialog block is the zc one, so it takes zc's head at the same offset from its box.
  usage: herofix.py <LensShapeHeroScenes.swift to write>   (also writes data/shapes/hero/hero.txt for tools/first-lens/shapes/stability)"""
import json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data', 'shapes', 'hero')
READS = [('h0', 0, 1.0), ('hc0', 0, 1.0), ('hc1', 1, 1.0), ('hc2', 2, 1.0), ('hc3', 3, 1.0), ('zc', 0, 0.887831), ('live', 0, 0.887831)]


def r1(v): return round(v, 1)


def head_of(words):
    """The first line's box from a block's words: they run line by line, and a line starts where y steps down by more than half a word's height."""
    out = [words[0]]
    for w in words[1:]:
        if w[3] - out[-1][3] > 0.5 * out[-1][5]: break
        out.append(w)
    x0 = min(w[2] for w in out); y0 = min(w[3] for w in out); x1 = max(w[2] + w[4] for w in out); y1 = max(w[3] + w[5] for w in out)
    return (r1(x0 / 2), r1(y0 / 2), r1((x1 - x0) / 2), r1((y1 - y0) / 2))


def load_jsonl(name):
    d = json.loads(open(os.path.join(DATA, name + '.jsonl')).readline())
    blocks = []
    for b in d['vn']:
        r = [v / 2 for v in b['r']]
        blocks.append([r1(r[0]), r1(r[1]), r1(r[2]), r1(r[3]), b['n'], head_of(b['w']) if b['n'] >= 2 and b.get('w') else None, b['t']])
    return (d['size'][0] / 2, d['size'][1] / 2), blocks


def load_live(zc):
    lines = open(os.path.join(DATA, 'live.txt')).read().splitlines()
    size = tuple(float(v) for v in lines[0].split()[3:5])
    blocks = []
    for l in lines[1:]:
        f = l.split(' ', 5)
        blocks.append([float(f[0]), float(f[1]), float(f[2]), float(f[3]), int(f[4]), None, f[5] if len(f) > 5 else ''])
    # the dialog block of the live take is zc's: its head sits at zc's offset from the block's box
    z = next(b for b in zc if b[6].startswith('Mira '))
    for b in blocks:
        if b[6].startswith('Mira ') and z[5]:
            b[5] = (r1(b[0] + z[5][0] - z[0]), r1(b[1] + z[5][1] - z[1]), z[5][2], z[5][3])
    return size, blocks


def main():
    reads = {}
    for name, _, _ in READS:
        if name != 'live': reads[name] = load_jsonl(name)
    reads['live'] = load_live(reads['zc'][1])
    sw = ['// Generated by tools/first-lens/shapes/herofix.py from the dumps of tools/first-lens/data/shapes/hero/ (the picker\'s vn read of the film stage,',
          '// hero2o 2026-10-22; `head` is a block\'s first line). Screen points: x, y, width, height, lines. Do not edit by hand.',
          'import CoreGraphics', '@testable import MwoyeoCore', '', 'enum LensShapeHeroScenes {',
          '    /// `dy`: how far below its place in `h0` the stage was pasted; `zoom`: the stage\'s scale (1 for hero.html, 0.888 for index.html).',
          '    struct Read { let name: String; let size: CGSize; let dy: CGFloat; let zoom: CGFloat; let blocks: [LensShape.Block] }',
          '    static func b(_ x: CGFloat, _ y: CGFloat, _ w: CGFloat, _ h: CGFloat, _ n: Int, head: CGRect? = nil) -> LensShape.Block {',
          '        LensShape.Block(core: CGRect(x: x, y: y, width: w, height: h), lines: n, head: head)', '    }',
          '    static let all: [Read] = [']
    for name, dy, zoom in READS:
        size, blocks = reads[name]
        sw.append('        Read(name: "%s", size: CGSize(width: %g, height: %g), dy: %g, zoom: %g, blocks: [' % (name, size[0], size[1], dy, zoom))
        for b in blocks:
            h = ', head: CGRect(x: %g, y: %g, width: %g, height: %g)' % b[5] if b[5] else ''
            sw.append('            b(%g, %g, %g, %g, %d%s),' % (b[0], b[1], b[2], b[3], b[4], h))
        sw.append('        ]),')
    sw += ['    ]', '}', '']
    open(sys.argv[1], 'w').write('\n'.join(sw))
    # the same reads as text for the stability probe (tools/first-lens/shapes/stability)
    tx = []
    for name, dy, zoom in READS:
        size, blocks = reads[name]
        tx.append('scene %s %g %g %g %g %d' % (name, size[0], size[1], dy, zoom, len(blocks)))
        for b in blocks:
            tx.append('%g %g %g %g %d %s' % (b[0], b[1], b[2], b[3], b[4], '%g %g %g %g' % b[5] if b[5] else '- - - -'))
    open(os.path.join(DATA, 'hero.txt'), 'w').write('\n'.join(tx) + '\n')
    print(len(READS), 'reads', sum(len(reads[n][1]) for n, _, _ in READS), 'blocks')


main()
