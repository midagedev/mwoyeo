"""ocrdump jsonl (vn read = the picker's lines path) -> per-scene block lists in screen pt (bench px / 2): data/shapes/scenes.txt (probe
input) and a Swift fixture for LensShapeTests.
  usage: tofix.py <LensShapeScenes.swift to write>"""
import json, glob, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, '..', 'data', 'shapes')
IDX = os.path.join(HERE, '..', '..', 'usecase-bench', 'set', 'index.tsv')
cat = {}
for l in open(IDX).read().splitlines()[1:]:
    n, uc, *_ = l.split('\t'); cat[n] = uc
scenes = []
for f in sorted(glob.glob(os.path.join(DATA, 'ocr', '*.jsonl'))) + [os.path.join(DATA, 'stage.ocr.jsonl')]:
    for l in open(f):
        d = json.loads(l)
        name = d['image']
        w, h = d['size'][0] / 2, d['size'][1] / 2
        bl = [(round(b['r'][0] / 2, 1), round(b['r'][1] / 2, 1), round(b['r'][2] / 2, 1), round(b['r'][3] / 2, 1), b['n'], b['t']) for b in d['vn']]
        scenes.append((name, cat.get(name, 'stage'), w, h, bl))
scenes.sort(key=lambda s: s[0])
with open(os.path.join(DATA, 'scenes.txt'), 'w') as o:
    for name, uc, w, h, bl in scenes:
        o.write('scene %s %s %g %g %d\n' % (name, uc, w, h, len(bl)))
        for b in bl:
            o.write('%g %g %g %g %d %s\n' % (b[0], b[1], b[2], b[3], b[4], b[5].replace('\n', ' ')[:50]))
sw = ['// Generated by tools/first-lens/shapes/tofix.py from ocrdump reads (the vn read: the picker\'s lines path, ParagraphGrouper) of the',
      '// use-case bench pictures (tools/usecase-bench/set, drawn at 2x) and of the stage (tools/first-lens/stage). Screen points: x, y, width,',
      '// height, lines. Do not edit by hand.', 'import CoreGraphics', '@testable import MwoyeoCore', '',
      'enum LensShapeScenes {', '    struct Scene { let name: String; let useCase: String; let size: CGSize; let blocks: [LensShape.Block] }',
      '    static func b(_ x: CGFloat, _ y: CGFloat, _ w: CGFloat, _ h: CGFloat, _ n: Int) -> LensShape.Block {',
      '        LensShape.Block(core: CGRect(x: x, y: y, width: w, height: h), lines: n)', '    }', '    static let all: [Scene] = [']
for name, uc, w, h, bl in scenes:
    sw.append('        Scene(name: "%s", useCase: "%s", size: CGSize(width: %g, height: %g), blocks: [' % (name, uc, w, h))
    for b in bl:
        sw.append('            b(%g, %g, %g, %g, %d),' % b[:5])
    sw.append('        ]),')
sw += ['    ]', '}', '']
open(sys.argv[1], 'w').write('\n'.join(sw))
print(len(scenes), 'scenes', sum(len(s[4]) for s in scenes), 'blocks')
