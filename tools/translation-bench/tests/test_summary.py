#!/usr/bin/env python3
"""runs/SUMMARY.md (G3): `python3 -I tests/test_summary.py`.

The file is generated by `summary.py` from the preserved runs and never edited by hand: two renders give the same bytes,
the committed file equals a fresh render (so a run added without regenerating, or a hand edit, fails here), and the
numbers of the two T1 runs on gemma3:4b come out as the T1b report pinned them."""
import importlib.util
import os
import sys
import tempfile
import unittest

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
BENCH = os.path.dirname(HERE)


def load(name):
    spec = importlib.util.spec_from_file_location(name, os.path.join(BENCH, name + ".py"))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


SM = load("summary")


class Summary(unittest.TestCase):
    def test_two_renders_are_byte_identical(self):
        a, b = SM.render(BENCH), SM.render(BENCH)
        self.assertEqual(a, b)
        print("two renders of runs/: %d bytes each, identical" % len(a.encode("utf-8")))

    def test_the_committed_file_is_current(self):
        path = os.path.join(BENCH, "runs", "SUMMARY.md")
        self.assertTrue(os.path.isfile(path), "runs/SUMMARY.md is missing; run `python3 -I summary.py`")
        with open(path, encoding="utf-8") as f:
            self.assertEqual(f.read(), SM.render(BENCH), "runs/SUMMARY.md is stale or hand-edited; run `python3 -I summary.py`")

    def test_a_hand_edit_is_caught_and_the_fresh_file_passes(self):
        with tempfile.TemporaryDirectory() as tmp:
            path = os.path.join(tmp, "SUMMARY.md")
            self.assertEqual(SM.main(["--root", BENCH, "--out", path]), 0)
            self.assertEqual(SM.main(["--root", BENCH, "--out", path, "--check"]), 0)
            with open(path, "a", encoding="utf-8") as f:
                f.write("a hand-written line\n")
            self.assertEqual(SM.main(["--root", BENCH, "--out", path, "--check"]), 1)
            os.remove(path)
            self.assertEqual(SM.main(["--root", BENCH, "--out", path, "--check"]), 1)

    def test_t1_numbers_and_the_sign_test_against_a(self):
        with tempfile.TemporaryDirectory() as tmp:
            os.makedirs(os.path.join(tmp, "runs"))
            for name in ("_corpus", "A-gemma3-4b", "M-gemma3-4b"):
                os.symlink(os.path.join(BENCH, "runs", name), os.path.join(tmp, "runs", name))
            text = SM.render(tmp)
        self.assertIn("| A-gemma3-4b | A | 80/312 | 25.6 | 15.1 | 19.5 | 66.0 | - | - | - | - | - |", text)
        self.assertIn("| M-gemma3-4b | M | 131/312 | 42.0 | 55.6 | 18.0 | 69.8 | +16.3 | <0.001 | +40.5 | <0.001 | A-gemma3-4b |", text)
        self.assertIn("| gemma3:4b | M-gemma3-4b | M | 42.0 | 55.6 | +16.3 | <0.001 | A-gemma3-4b | 25 (4) | 38 + 8 | 0 | 14 | 323 | 1895 |", text)
        self.assertNotIn("A-gemma3-4b-r2", text)


if __name__ == "__main__":
    unittest.main(verbosity=2)
